inline void fill(HDC dc, int x, int y, int w, int h, COLORREF c) {
    if (w <= 0 || h <= 0) return;
    RECT r{x, y, x + w, y + h};
    HBRUSH b = CreateSolidBrush(c);
    FillRect(dc, &r, b);
    DeleteObject(b);
}
/// A bar with round ends: each row inset by the circle of radius h / 2
inline void round_fill(HDC dc, int x, int y, int w, int h, COLORREF c) {
    if (w <= 0 || h <= 0) return;
    const double r = std::min(w, h) / 2.0;
    for (int row = 0; row < h; row++) {
        const double dy = std::fabs(row + 0.5 - h / 2.0);
        const double half = dy < r ? std::sqrt(r * r - dy * dy) : 0;
        const int inset = (int)std::lround(r - half);
        fill(dc, x + inset, y + row, w - 2 * inset, 1, c);
    }
}
/// A rectangle with corners rounded to radius r (the Insert menu's selected row)
inline void round_rect(HDC dc, int x, int y, int w, int h, int r, COLORREF c) {
    if (w <= 0 || h <= 0) return;
    r = std::max(0, std::min({r, w / 2, h / 2}));
    for (int row = 0; row < h; row++) {
        const int d = row < r ? r - row : row >= h - r ? row - (h - r) + 1 : 0;   // (rows into the corner's curve)
        const int inset = d ? (int)std::lround(r - std::sqrt((double)r * r - (double)(d - 0.5) * (d - 0.5))) : 0;
        fill(dc, x + inset, y + row, w - 2 * inset, 1, c);
    }
}
inline int text_w(HDC dc, const std::string& t) {
    SIZE sz{};
    GetTextExtentPoint32A(dc, t.c_str(), (int)t.size(), &sz);
    return (int)sz.cx;
}
/// Spaced capitals, centred on cx (or from x when left): letter by letter, gap pixels apart
inline void spaced(HDC dc, const std::string& t, int x, int y, int gap, bool centre) {
    int total = 0;
    for (char ch : t) total += text_w(dc, std::string(1, ch)) + gap;
    total -= gap;
    int at = centre ? x - total / 2 : x;
    SetTextAlign(dc, TA_LEFT | TA_TOP);
    for (char ch : t) {
        TextOutA(dc, at, y, &ch, 1);
        at += text_w(dc, std::string(1, ch)) + gap;
    }
}
