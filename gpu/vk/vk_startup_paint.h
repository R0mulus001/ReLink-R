/// The game's own typeface (assets/fonts, nx2/fonts_embed.py) for this process alone, once: false when it is not there (a
/// build without it, Linux), and the screen then uses the system's
inline bool startup_fonts() {
#if defined(RELINK_FONTS) && defined(_WIN32)
    static const bool ok = [] {
        int added = 0;
        for (int i = 0; i < 4; i++) {
            DWORD n = 0;
            if (AddFontMemResourceEx((void*)relink_fonts[i], relink_font_sizes[i], nullptr, &n) && n) added++;
        }
        return added == 4;
    }();
    return ok;
#else
    return false;
#endif
}

